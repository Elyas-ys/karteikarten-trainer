import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const inputDir = path.join(projectRoot, "Karteikarten JSON");
const outputFile = path.join(projectRoot, "project-data.js");

const entries = await readdir(inputDir, { withFileTypes: true });
const jsonFiles = entries
  .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, "de"));

const sources = [];

for (const fileName of jsonFiles) {
  const filePath = path.join(inputDir, fileName);
  const sourcePath = path.posix.join("Karteikarten JSON", fileName);
  const payload = JSON.parse(await readFile(filePath, "utf8"));

  sources.push({
    source: sourcePath,
    payload,
  });
}

const output = `// Generated by scripts/build-project-data.mjs. Do not edit by hand.
window.projectCardImports = ${JSON.stringify(sources, null, 2)};
`;

await writeFile(outputFile, output);

console.log(
  `Generated ${path.relative(projectRoot, outputFile)} from ${jsonFiles.length} JSON file(s).`,
);
